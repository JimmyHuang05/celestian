"""Capture the approved SVGs for bundling; retain vector paths unchanged."""
import json
import re
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[2]
legacy = root.parent / 'archive/celestian/public/shared/encyclopedia-icon-motion-v2.js'
text = legacy.read_text(encoding='utf-8')
start = text.index('const assets=') + len('const assets=')
assets, end = json.JSONDecoder().raw_decode(text[start:])
assets['enemies'] = assets.pop('dragon')
for kind, name in [('aeons', 'deity-vortex-gothic-20261012.svg'), ('relics', 'relics.svg'), ('terms', 'terms.svg')]:
    url = 'https://assets.jimmyhuang.cn/celestian/images/icons/' + name
    with urllib.request.urlopen(url, timeout=30) as response:
        svg = response.read().decode('utf-8-sig')
    node = ET.fromstring(svg)
    for element in node.iter():
        assert element.tag.split('}')[-1] not in ['script', 'foreignObject', 'image']
        assert not any(key.lower().startswith('on') for key in element.attrib)
        assert not any(key.split('}')[-1] == 'href' and not value.startswith('#') for key, value in element.attrib.items())
    # Remove XML declaration/comments, not path coordinates or paint instructions.
    svg = re.sub(r'<\?xml.*?\?>|<!--.*?-->', '', svg, flags=re.S).strip()
    assets[kind] = svg
out = root / 'src/components/encyclopedia'
(out / 'node-emblems.js').write_text('// Approved local vector artwork. Generated by scripts/assets/prepare-node-emblems.py.\nexport default ' + json.dumps(assets, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
functions = text[start+end:].lstrip(';\r\n')
functions = functions[:functions.index('const seen=')]
(out / 'node-emblem-motion.js').write_text(functions, encoding='utf-8')
print({key: len(value.encode('utf-8')) for key, value in assets.items()})
