const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_BIN || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } }), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto((process.env.PREVIEW_URL || 'http://127.0.0.1:5173') + '/map/')
    await page.waitForFunction(() => document.querySelectorAll('.map-territories [role=button]').length === 82)
    assert.equal(await page.locator('[data-marker-id]').count(), 67)
    const region = page.locator('.map-territories [role=button]').first()
    await region.dispatchEvent('pointerover', { pointerType: 'mouse' })
    assert.equal(await region.evaluate(e => e.style.strokeWidth), '2')
    await region.dispatchEvent('pointerout', { pointerType: 'mouse' })
    await region.press('Enter')
    await page.getByRole('complementary', { name: '区域资料' }).waitFor()
    assert(await page.locator('.map-territories [data-selected]').count() > 1)
    assert(await page.locator('.map-region-preview svg path').count() > 1)
    await page.screenshot({ path: path.join(__dirname, '../../design/map-region-restored.png') })
    await page.getByRole('button', { name: '关闭资料卡' }).click()
    await page.locator('.map-marker-detail').waitFor({ state: 'detached' })
    assert.equal(await page.locator('.map-territories [data-selected]').count(), 0)
    await page.getByRole('button', { name: /^首都 7$/ }).click()
    assert.equal(await page.locator('[data-marker-id]').evaluateAll(es => es.filter(e => e.style.display !== 'none').length), 7)
    await page.getByRole('button', { name: /^全部 67$/ }).click()
    const input = page.getByRole('combobox', { name: '搜索地点或区域' })
    await input.fill('新琥珀')
    await page.getByRole('listbox', { name: '搜索结果' }).getByRole('option').first().click()
    await page.getByRole('complementary', { name: '地点资料' }).waitFor()
    await input.fill('奥兰尼亚')
    await page.getByRole('listbox', { name: '搜索结果' }).getByRole('option').first().click()
    await page.getByRole('complementary', { name: '区域资料' }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.waitForTimeout(400)
    await page.screenshot({ path: path.join(__dirname, '../../design/map-region-restored-mobile.png') })
    await page.getByRole('button', { name: '关闭资料卡' }).click()
    await page.locator('.map-marker-detail').waitFor({ state: 'detached' })
    await page.getByRole('button', { name: '地图显示设置' }).click()
    await page.getByRole('button', { name: '回到地图中心' }).click()
    await page.getByRole('button', { name: '查看全图' }).click()
    assert.deepEqual(errors, [])
    console.log('Passed: region hover, related highlighting, preview, reset, capital filter, point and region search, mobile detail, center and full view.')
  } finally { await browser.close() }
})().catch(e => { console.error(e.message); process.exit(1) })
