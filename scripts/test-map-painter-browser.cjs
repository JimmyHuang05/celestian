const { createHash } = require('node:crypto')
const path = require('node:path')
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5173'
const digest = value => createHash('sha256').update(JSON.stringify(value)).digest('hex')

async function download(page, button) {
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: button, exact: true }).click()
  const result = await pending, chunks = []
  for await (const chunk of await result.createReadStream()) chunks.push(chunk)
  return Buffer.concat(chunks)
}
const backup = async page => JSON.parse(await download(page, '下载备份'))
function cells(data) {
  const result = new Map()
  for (const tile of data.tiles) for (const [start, length, id] of tile.runs) for (let i = start; i < start + length; i++) result.set(`${tile.key}:${i}`, id)
  return result
}
async function ready(page) {
  await page.getByRole('button', { name: '新增国家' }).waitFor()
  await page.waitForFunction(() => !document.querySelector('button[aria-label="新增国家"]').disabled)
  await page.locator('.leaflet-tile-loaded').first().waitFor()
  await page.waitForTimeout(700)
}
async function position(page, x, y) {
  return page.evaluate(({ x, y }) => {
    const image = document.querySelector('img.leaflet-tile-loaded')
    const match = image.src.match(/world-240705-base-v2\/(\d+)\/(\d+)\/(\d+)\.webp/)
    const [, z, tx, ty] = match.map(Number), rect = image.getBoundingClientRect(), side = 512 * 2 ** (6 - z)
    return { x: rect.left + (x - tx * side) / side * rect.width, y: rect.top + (y - ty * side) / side * rect.height }
  }, { x, y })
}

