const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/admin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5173'
const key = 'celestian-map-view-v2'
const input = p => p.getByRole('combobox', { name: '搜索地点或区域' })
const count = p => p.locator('[data-marker-id]').evaluateAll(es => es.filter(e => e.style.display !== 'none').length)
const errors = [], badTiles = []
async function ready(page, navigate = true) {
  if (navigate) await page.goto(base + '/map/')
  await page.waitForFunction(() => document.querySelectorAll('.map-territories [role=button]').length === 82)
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(600)
}
async function select(p, text) { await input(p).fill(text); await input(p).press('Enter'); await p.waitForTimeout(650) }
async function prefs(p) { return p.evaluate(k => JSON.parse(localStorage.getItem(k)), key) }
async function close(p) { await p.getByRole('button', { name: '关闭资料卡' }).click(); await p.locator('.map-marker-detail').waitFor({ state: 'detached' }) }
async function settings(p) {
  if (await p.getByRole('button', { name: '关闭图层设置' }).count()) await p.getByRole('button', { name: '关闭图层设置' }).click()
  else await p.getByRole('button', { name: '地图显示设置' }).click()
}
async function wholeExtent(p) {
  return p.locator('.map-territories [data-selected]').evaluateAll(es => {
    const r = es.map(e => e.getBoundingClientRect())
    return { left: Math.min(...r.map(b => b.left)), right: Math.max(...r.map(b => b.right)), top: Math.min(...r.map(b => b.top)), bottom: Math.max(...r.map(b => b.bottom)) }
  })
}
;(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_BIN || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
    page.on('pageerror', e => errors.push(e.message))
    const checkTile = r => { if (r.url().includes('/world-240705-base-v2/') && /\.webp$/.test(r.url()) && r.status() >= 400) badTiles.push({ url: r.url(), status: r.status() }) }
    page.on('response', checkTile)
    await ready(page)
    const overviewCount = await count(page)
    assert(overviewCount > 7 && overviewCount < 40, 'Overview should be decluttered')
    assert.equal(await page.locator('[aria-label="北港"][data-marker-id]').isVisible(), false)
    const before = await page.locator('.map-labels-overlay').boundingBox()
    await select(page, '北港')
    assert(await page.locator('.geo-pin-map-active').isVisible())
    assert((await count(page)) > overviewCount, 'Zooming reveals more places')
    await page.getByRole('button', { name: '返回上一视图' }).click()
    await page.waitForTimeout(650)
    const after = await page.locator('.map-labels-overlay').boundingBox()
    assert(Math.abs(before.x - after.x) < 2 && Math.abs(before.y - after.y) < 2 && Math.abs(before.width - after.width) < 2)

    await settings(page)
    await page.getByRole('button', { name: '显示地点标记' }).click()
    assert.equal(await count(page), 0)
    await settings(page)
    await select(page, '北港')
    assert.equal(await count(page), 1, 'A search-selected point survives the hidden point layer')
    await close(page)
    assert.equal(await count(page), 0)

    await select(page, '奥兰尼亚')
    const mainZoom = (await prefs(page)).view.zoom
    await page.getByRole('button', { name: '全部领土', exact: true }).click()
    await page.waitForTimeout(650)
    assert((await prefs(page)).view.zoom < mainZoom)
    let extent = await wholeExtent(page)
    assert(extent.left >= 407 && extent.right <= 1361 && extent.top >= 141 && extent.bottom <= 905, JSON.stringify(extent))
    const selectedView = await prefs(page)
    await page.reload(); await ready(page, false)
    assert.equal(await page.locator('.map-marker-detail h2').textContent(), '女王陛下的奥兰尼亚帝国')
    assert.equal((await prefs(page)).view.zoom, selectedView.view.zoom)
    extent = await wholeExtent(page)
    assert(extent.left >= 407 && extent.right <= 1361)
    const selectedCount = await page.locator('.map-territories [data-selected]').count()
    const other = page.locator('.map-territories [data-region-id="region_70_1_2"]')
    await other.dispatchEvent('pointerover', { pointerType: 'mouse', clientX: 700, clientY: 300 })
    await page.locator('.map-region-tooltip').waitFor()
    assert((await page.locator('.map-region-tooltip').innerText()).includes('伊斯塔维拉王国'))
    assert.equal(await page.locator('.map-territories [data-selected]').count(), selectedCount)
    await other.dispatchEvent('pointerout')
    await close(page)

    await settings(page)
    await page.getByRole('button', { name: '显示国家疆域' }).click()
    await page.getByRole('button', { name: '显示特殊状态' }).click()
    await page.getByRole('button', { name: '显示地图文字' }).click()
    await page.locator('.map-legend summary').click()
    assert((await page.locator('.map-legend__countries>div').count()) >= 9)
    assert((await page.locator('.map-legend__points>div').count()) >= 7)
    await page.waitForTimeout(250)
    const region = page.locator('.map-territories [data-region-id="region_40_2"]')
    const color = await region.evaluate(e => e.style.fill)
    assert.notEqual(color, 'transparent')
    await settings(page)
    await page.getByRole('button', { name: /^首都 7$/ }).click()
    assert.equal(await count(page), 7)
    await input(page).fill('奥兰尼亚')
    await input(page).press('Escape')
    const stored = await prefs(page), viewBeforeReload = await page.locator('.map-labels-overlay').boundingBox()
    await page.reload(); await ready(page, false)
    const storedAgain = await prefs(page), viewAfterReload = await page.locator('.map-labels-overlay').boundingBox()
    assert.deepEqual(storedAgain.layers, stored.layers)
    assert.equal(storedAgain.type, '首都')
    assert.equal(await input(page).inputValue(), '奥兰尼亚')
    assert.equal(await page.locator('.map-labels-overlay').isVisible(), false)
    assert.equal(await page.getByRole('listbox').count(), 0, 'Restore does not reopen search')
    assert.equal(await count(page), 7)
    assert(Math.abs(viewBeforeReload.x - viewAfterReload.x) < 2 && Math.abs(viewBeforeReload.y - viewAfterReload.y) < 2)
    await settings(page)
    await page.getByRole('button', { name: '恢复默认地图' }).click()
    await page.waitForTimeout(650)
    const reset = await prefs(page)
    assert.deepEqual(reset.layers, { labels: true, points: true, countries: false, statuses: true })
    assert.equal(reset.type, ''); assert.equal(reset.query, '')
    assert.equal(await page.getByRole('button', { name: '返回上一视图' }).count(), 0)
    await page.screenshot({ path: path.join(__dirname, '../../design/map-phase2-desktop-final.png') })

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    mobile.on('pageerror', e => errors.push(e.message))
    mobile.on('response', checkTile)
    await ready(mobile)
    await select(mobile, '奥兰尼亚')
    const mobileMain = (await prefs(mobile)).view.zoom
    await mobile.getByRole('button', { name: '全部领土', exact: true }).click()
    await mobile.waitForTimeout(650)
    extent = await wholeExtent(mobile)
    assert((await prefs(mobile)).view.zoom < mobileMain)
    assert(extent.left >= 23 && extent.right <= 367 && extent.top >= 131 && extent.bottom <= 380, JSON.stringify(extent))
    const tools = await mobile.locator('.tiled-map__controls').boundingBox(), card = await mobile.locator('.map-marker-detail').boundingBox()
    assert(tools.y + tools.height < card.y)
    await settings(mobile)
    await mobile.getByRole('button', { name: '显示国家疆域' }).click()
    await mobile.locator('.map-legend summary').click()
    await mobile.waitForTimeout(250)
    const panel = await mobile.locator('.map-display-panel').boundingBox()
    assert(panel.y >= 120 && panel.y + panel.height <= 844)
    await mobile.screenshot({ path: path.join(__dirname, '../../design/map-phase2-mobile-final.png') })
    await settings(mobile)
    await mobile.getByRole('button', { name: '查看主要领土' }).click()
    await mobile.waitForTimeout(650)
    assert.equal((await prefs(mobile)).view.zoom, mobileMain)
    await mobile.setViewportSize({ width: 320, height: 844 })
    await mobile.getByRole('button', { name: '查看全图' }).click()
    await mobile.waitForTimeout(650)
    assert((await mobile.locator('.map-labels-overlay').boundingBox()).width <= 320)
    assert.deepEqual(errors, [])
    assert.deepEqual(badTiles, [])
    console.log('Passed: point levels/overlap, search exceptions, previous view, main/all territory framing, hover while selected, independent layers/legend, reload persistence, reset and mobile/320px overview.')
  } finally { await browser.close() }
})().catch(error => { console.error(error.stack); process.exit(1) })
